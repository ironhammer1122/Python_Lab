import tkinter as tk

# Q1
window = tk.Tk()
window.title("Student Window")
window.geometry("300x200")
heading = tk.Label(window, text="Enter your city:")
heading.pack()
city_entry = tk.Entry(window)
city_entry.pack()
submit_btn = tk.Button(window, text="Continue")
submit_btn.pack()
window.mainloop()

